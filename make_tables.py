"""Generate paper/numbers.tex and paper/tab_*.tex from results/*.json (single source of truth)."""
import json, sys, time, platform
import numpy as np, scipy, qutip, torch

R = lambda f: json.load(open(f"results/{f}"))
sc, rb, tr = R("scaling.json"), R("robustness.json"), R("transient_seed0.json")
ews, ewa, sh = R("ews_symmetric.json"), R("ews_asymmetric.json"), R("ews_excitation_shift.json")
N = {}
pct = lambda x, d=1: f"{100*x:.{d}f}\\%"

# versions
N.update(pythonVersion=platform.python_version(), numpyVersion=np.__version__, scipyVersion=scipy.__version__,
         qutipVersion=qutip.__version__, torchVersion=torch.__version__.split("+")[0])
# scaling
r4 = [x for x in sc["Tj_sweep_a1.0"] if x["Tj"] == 4.0][0]
N.update(fOpFour=f"{r4['f_op']:.3f}", fFullFour=f"{r4['f_full']:.3f}", fInvTjFour=f"{r4['f_invTj']:.3f}",
         invTjErr=f"{100*(r4['f_invTj']/r4['f_full']-1):+.0f}\\%".replace("+", "$+$"),
         aStarFiveOp=f"{sc['a_star']['0.05']['op']:.3f}", aStarFiveFull=f"{sc['a_star']['0.05']['full']:.3f}")
# test-system modes at calibration point
import model as m
f, z = m.interarea(0.25, 8.0)
N.update(fIp=f"{f[0]:.3f}", zIp=pct(z[0]), fIa=f"{f[1]:.3f}", zIa=pct(z[1]))
# robustness
nb, lb = rb["nominal"], rb["local"]
N.update(robN=str(rb["N"]), robFmax=pct(nb["f_relerr"]["max"], 2), robZmax=f"{nb['z_abserr']['max']:.4f}",
         robCommMax=f"{max(nb['comm']['max'], lb['comm']['max']):.3f}",
         robTransMax=pct(max(nb['nrmse_op_reduced']['max'], lb['nrmse_op_reduced']['max']), 2),
         robCorr=f"{nb['corr_comm_vs_transform_error']:.2f}", robNrmseNF=pct(nb["nrmse_op_full"]["p95"]),
         robNrmseMax=pct(nb["nrmse_op_full"]["max"]), robNrmseNFloc=pct(lb["nrmse_op_full"]["p95"]),
         robNrmseMaxloc=pct(lb["nrmse_op_full"]["max"]),
         robLindFrac=f"{sum(r['lindblad_ok'] for r in rb['rows'])}/{len(rb['rows'])}")
# transient
nom, S1, S2 = tr["nominal"], tr["S1_automation_step"], tr["S2_inertia_cut"]
N.update(noiseMHz=f"{tr['noise_mHz']:.1f}", opRecon=f"{nom['Operator model (forward)']['rmse']:.3f}",
         prePostS=f"{S1['pre_post_difference']:.2f}", opPredS=f"{S1['Operator model (algebraic update)']['rmse']:.3f}",
         opUpdateUs=f"{1e6*S1['Operator model (algebraic update)']['update_s']:.0f}")
from common import operator_response, reduced_classical_response, T
N["opVsRedRecon"] = f"{np.sqrt(np.mean((operator_response(0.25, 8.0)-reduced_classical_response(0.25, 8.0))**2)):.4f}"
k_no, k_re = "SFQ circuit (trained pre-change, not retrained)", "SFQ circuit (re-trained on post-change record)"
N.update(sfqNoRetrainS=f"{S1[k_no]['rmse']:.2f}", sfqRetrainTimeS=f"{S1[k_re]['update_s']:.0f}",
         sfqRetrainS=f"{S1[k_re]['rmse']:.2f}", pinnPreFit=f"{S1['PINN (trained pre-change, not retrained)']['pre_rmse']:.3f}",
         ppinnS=f"{S1['Parametric PINN (t, a), a in [0, 0.6]']['rmse']:.2f}")
# timing
import operator_model as om
M, D = m.machine_params(0.25); K = m.stiffness(); Wa = m.slow_basis()
Mr, Dr, Kr = m.reduce(M, D, K, Wa); x0 = om.project(M, Wa, np.zeros(4)); xd0 = om.project(M, Wa, np.array([0, 0, -.1, -.1]))
ts = []
for _ in range(20):
    t0 = time.perf_counter(); om.run_operator(Mr, Dr, Kr, x0, xd0, T); ts.append(time.perf_counter() - t0)
tc = []
for _ in range(20):
    t0 = time.perf_counter(); om.run_reduced_classical(Mr, Dr, Kr, x0, xd0, T); tc.append(time.perf_counter() - t0)
N.update(mesolveMs=f"{1e3*np.median(ts):.0f}", classicalMs=f"{1e3*np.median(tc):.1f}")
# early warning
L = ews["lead"]
N.update(leadMentMed=f"{L['Ment']['median']:.0f}", leadMentLo=f"{L['Ment']['ci95'][0]:.0f}", leadMentHi=f"{L['Ment']['ci95'][1]:.0f}",
         leadMmMed=f"{L['zeta_mm']['median']:.0f}", leadVarMed=f"{L['var']['median']:.0f}",
         farMentRef=pct(ews["far_at_a_ref"]["Ment"]), farVarShift=pct(sh["excitation_x2.0_nominal"]["var"], 0),
         farMentShift=pct(sh["excitation_x2.0_nominal"]["Ment"]), rampEnd=f"{ews['ramp'][1]:.2f}",
         tRef=f"{ews['t_ref']:.0f}", tZero=f"{ews['t_zero']:.0f}", tVisMean=f"{ews['t_visible']['mean']:.0f}",
         tVisSd=f"{ews['t_visible']['sd']:.0f}", aRef=f"{ews['a_ref']:.3f}")
with open("paper/numbers.tex", "w") as fh:
    fh.write("%% generated by make_tables.py -- do not edit\n")
    for k, v in N.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

